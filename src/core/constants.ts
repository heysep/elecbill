/**
 * 급여별 선정기준 = 기준 중위소득 × 비율. 2026·2027년 모두 비율은 같다.
 * 보도자료 원문: "급여별 선정기준은 기준 중위소득 대비 일정 비율을 적용하여 결정하며,
 * 2027년에는 올해와 동일하게 생계급여 32%, 의료급여 40%, 주거급여 48%, 교육급여 50%로 결정"
 *
 * 1차 출처: 위 보도자료 PDF 6쪽 <2026년도 및 2027년도 급여별 선정기준> (확인일 2026-09-14)
 *
 * 발표된 48개 금액이 전부 round(중위소득 × 비율) 과 원 단위까지 일치한다 —
 * 그래서 표를 또 박지 않고 계산한다(constants.test.ts 가 발표값 48개와 전수 대조한다).
 */
export const BENEFIT_RATE = {
  /** 생계급여 32% — 임차급여 자기부담분의 기준선이기도 하다 */
  living: 0.32,
  /** 의료급여 40% */
  medical: 0.4,
  /** 주거급여 48% */
  housing: 0.48,
  /** 교육급여 50% */
  education: 0.5,
} as const;

export type BenefitKind = keyof typeof BENEFIT_RATE;

/** 급여별 선정기준(원/월). 발표값과 원 단위까지 같다. */
export function selectionLine(year: Year, people: number, kind: BenefitKind): number {
  const median = MEDIAN_INCOME[year][clampPeople(people) - 1];
  return Math.round(median * BENEFIT_RATE[kind]);
}

export function clampPeople(people: number): number {
  if (!Number.isFinite(people)) return 1;
  return Math.min(Math.max(Math.floor(people), 1), MAX_PEOPLE);
}

